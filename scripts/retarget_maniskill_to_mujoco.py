#!/usr/bin/env python3
"""Convert ManiSkill Panda demonstrations into robosuite / MuJoCo HDF5.

This is a cross-simulator trajectory retargeter, not a lossless converter.
ManiSkill joint-position targets are tracked by a robosuite Panda in MuJoCo and
By default, every recorded PhysX state is mapped into the faithful MuJoCo task
port. This avoids accumulating cross-simulator contact and controller drift.
The resulting MuJoCo states, observations, actions, and wrist wrench are saved
in robomimic / MimicGen-compatible HDF5 format. An open-loop replay mode is
also available for measuring cross-simulator reproducibility.

The wrench samples are generated by MuJoCo. They are not measurements recovered
from PhysX and are meaningful only to the extent that the selected robosuite
task, geometry, controller, and trajectory reproduce the intended interaction.
"""

